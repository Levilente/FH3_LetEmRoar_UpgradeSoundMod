import struct,sys,os
def analyse(path):
    d=open(path,'rb').read(); out=[]
    def walk(o,end):
        while o+8<=end:
            cid=d[o:o+4]; sz=struct.unpack_from('<I',d,o+4)[0]
            if cid in (b'RIFF',b'LIST'):
                out.append(('L:'+d[o+8:o+12].decode('latin1'),o+12,sz-4)); walk(o+12,o+8+sz)
            else: out.append((cid.decode('latin1'),o+8,sz))
            o+=8+sz+(sz&1)
    walk(0,len(d))
    objs={}; pmlos=[]; wavs={}; pn={}; snd=None
    for c,o,sz in out:
        if c=='WAV ': wavs[d[o:o+16]]=d[o:o+sz]
        if c=='SND ': snd=(o,sz)
        if c=='PRMB':
            b=d[o:o+sz]; n=struct.unpack_from('<H',b,21)[0]; pn[b[:16]]=b[23:23+n].split(b'\0')[0].decode('latin1')
        if c.startswith('L:') and len(c)==6:
            body={}; first=None
            for c2,o2,s2 in out:
                if o<=o2<o+sz and not c2.startswith('L:'):
                    if first is None: first=(c2,o2,s2)
                    body.setdefault(c2,(o2,s2))
            if not first or len(first[0])!=4 or first[0][-1]!='B': continue
            gid=d[first[1]:first[1]+16]
            if c[2:]=='PMLO': pmlos.append(body)
            else: objs[gid]=(c[2:],body)
    def chunk(gid,n):
        o,s=objs[gid][1][n]; return d[o:o+s]
    def lst(b,off):
        if off+4>len(b): return []
        t,es=struct.unpack_from('<HH',b,off)
        if not (t&1) or es<16: return []
        return [b[off+4+i*es:off+4+i*es+16] for i in range(t>>1)]
    def event_insts(ev):
        res=[]
        for gid,(t,ch) in objs.items():
            if t=='TMLN':
                b=chunk(gid,'TLNB')
                if b[16:32]==ev: res+=lst(b,32)
        for ch in pmlos:
            o,s=ch['PMLB']; b=d[o:o+s]
            if b[32:48]==ev: res+=lst(b,48)
        return res
    def resolve(gid,acc,seen,stop):
        if gid in seen or gid not in objs or gid in stop: return
        seen.add(gid); t=objs[gid][0]
        try:
            if t=='WAIT':
                w=wavs.get(chunk(gid,'WAIB')[16:32])
                if w: acc.add(struct.unpack_from('<H',w,22)[0])
            elif t=='MUIT':
                b=chunk(gid,'PLST'); n=(len(b)-12)//20
                for i in range(n): resolve(b[12+i*20:28+i*20],acc,seen,stop)
            elif t=='EVIT': resolve(chunk(gid,'EVIB')[16:32],acc,seen,stop)
            elif t=='EVNT':
                for i in event_insts(gid): resolve(i,acc,seen,stop)
        except KeyError: pass
    nested=set()
    for gid,(t,ch) in objs.items():
        if t=='EVIT':
            try: nested.add(chunk(gid,'EVIB')[16:32])
            except KeyError: pass
    def evs_with(name):
        gs=[g for g,n in pn.items() if n==name]
        r=[]
        for ev in nested:
            if ev in objs and objs[ev][0]=='EVNT':
                b=chunk(ev,'EVTB')
                if any(b.find(g)>=0 for g in gs): r.append(ev)
        return r
    exh_ev=evs_with('ExhaustUpgradeLevel'); eng_ev=evs_with('EngineUpgradeLevel')
    exh=set(); eng=set(); allw=set()
    for e in exh_ev: resolve(e,exh,set(),set())
    for e in eng_ev: resolve(e,eng,set(),set(exh_ev))
    eng-=exh
    i=d.find(b'FSB5')
    if i<0: return None
    n=struct.unpack_from('<I',d,i+8)[0]
    return dict(off=i,len=len(d)-i,n=n,exh=sorted(k for k in exh if k<n),eng=sorted(k for k in eng if k<n),ne=len(exh_ev),ng=len(eng_ev))
if __name__=='__main__':
    src=sys.argv[1]; rows=[]; stats=[]
    for f in sorted(os.listdir(src)):
        if not f.endswith('.bank') or not (f.startswith('PG_') or f.startswith('GS_')): continue
        try: r=analyse(os.path.join(src,f))
        except Exception as e: stats.append((f,'ERR '+str(e))); continue
        if not r: stats.append((f,'nofsb')); continue
        stats.append((f,r['n'],len(r['exh']),len(r['eng']),r['ne'],r['ng']))
        def mask(l):
            m=[0,0,0,0,0,0,0,0]
            for k in l:
                if k<512: m[k>>6]|=1<<(k&63)
            return ','.join('0x%xull'%x for x in m)
        rows.append('    {%d, %d, {%s}, {%s}},   // %s'%(r['off'],r['len'],mask(r['exh']),mask(r['eng']),f))
    open(sys.argv[2],'w').write('// generated by tools/tiers_table.py from the game\'s car sound banks: sample data offset in the bank, its length, exhaust samples, engine-bay samples (bit = sample index)\nconst BankTier kBankTier[] = {\n'+'\n'.join(rows)+'\n};\n')
    import collections
    print(len(rows),'banks')
    print('no exhaust:',[s[0] for s in stats if len(s)>2 and s[2]==0][:40])
    print('no engine:',[s[0] for s in stats if len(s)>2 and s[3]==0][:40])
    print('max n',max(s[1] for s in stats if len(s)>2))
    print(stats[:6]); print([s for s in stats if len(s)==2])
